// =====================================================================
//  POST /api/check-links  (ADMIN)
//  body: { id }  -> check one project      (omit id to check all projects)
//
//  For each project link the server fetches the page and records:
//    link_ok          true only when the page answers 200 AND looks like a real page
//    link_status      HTTP status (null when the request failed)
//    link_note        short reason when not ok (admin only)
//    link_checked_at  time of the check
//
//  A bare 200 is not trusted: a CDN configured to turn 403/404 into index.html answers
//  200 for a broken site. So the body is also checked for common error pages
//  (CloudFront / S3 AccessDenied, NoSuchKey, 403/404 titles) and for being empty.
// =====================================================================
import { sql, setCors, parseBody, requireRole } from "./_lib.js";
import { isPublicHost } from "./_works-util.js";

const TIMEOUT_MS = 8000;
const MAX_BYTES = 150000;

async function readLimited(res) {
  const reader = res.body && res.body.getReader ? res.body.getReader() : null;
  if (!reader) return (await res.text()).slice(0, MAX_BYTES);
  const dec = new TextDecoder("utf-8", { fatal: false });
  let out = "", total = 0;
  while (total < MAX_BYTES) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.length;
    out += dec.decode(value, { stream: true });
  }
  try { await reader.cancel(); } catch { /* ignore */ }
  return out;
}

const ERROR_SIGNATURES = [
  [/<Code>\s*(AccessDenied|NoSuchKey|NoSuchBucket)\s*<\/Code>/i, "Storage error page (AccessDenied / NoSuchKey)"],
  [/The request could not be satisfied|Generated by cloudfront/i, "CloudFront error page"],
  [/<title>[^<]*\b(403|404|502|503)\b[^<]*<\/title>/i, "Error page title (403/404/50x)"],
  [/<title>\s*(Access Denied|Forbidden|Not Found|Page Not Found|Site not found)\s*<\/title>/i, "Error page title"],
  [/DEPLOYMENT_NOT_FOUND/, "Hosting says deployment not found"],
];

export async function checkUrl(url) {
  const out = { ok: false, status: null, note: null };
  let host;
  try { host = new URL(url).hostname; } catch { out.note = "Invalid URL"; return out; }
  if (!isPublicHost(host)) { out.note = "Not a public host"; return out; }

  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
  try {
    const res = await fetch(url, {
      method: "GET",
      redirect: "follow",
      signal: ctrl.signal,
      headers: { "User-Agent": "AIForAll-LinkCheck/1.0", Accept: "text/html,application/xhtml+xml,*/*;q=0.8" },
    });
    out.status = res.status;
    if (res.status !== 200) { out.note = `HTTP ${res.status}`; try { await res.body?.cancel(); } catch { /* ignore */ } return out; }

    const ct = (res.headers.get("content-type") || "").toLowerCase();
    const body = await readLimited(res);
    if (!ct.includes("html")) { out.note = `Not an HTML page (${ct || "no content-type"})`; return out; }
    if (body.trim().length < 50) { out.note = "Page is empty"; return out; }
    for (const [re, why] of ERROR_SIGNATURES) {
      if (re.test(body)) { out.note = why; return out; }
    }
    out.ok = true;
    return out;
  } catch (err) {
    out.note = err && err.name === "AbortError" ? `No answer within ${TIMEOUT_MS / 1000}s` : "Could not connect";
    return out;
  } finally {
    clearTimeout(timer);
  }
}

export default async function handler(req, res) {
  setCors(res);
  if (req.method === "OPTIONS") return res.status(200).end();
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed." });

  const admin = requireRole(req, res, "admin");
  if (!admin) return;

  try {
    const { id } = parseBody(req);
    const works = id
      ? await sql`SELECT id, project_url FROM pjt_works WHERE id = ${id}`
      : await sql`SELECT id, project_url FROM pjt_works`;
    if (id && !works[0]) return res.status(404).json({ error: "Project not found." });

    const results = await Promise.all(
      works.map(async (w) => {
        const r = await checkUrl(w.project_url);
        await sql`
          UPDATE pjt_works
          SET link_ok = ${r.ok}, link_status = ${r.status}, link_note = ${r.note}, link_checked_at = NOW()
          WHERE id = ${w.id}
        `;
        return { id: w.id, ok: r.ok, status: r.status, note: r.note };
      })
    );
    return res.status(200).json({ success: true, results, checked: results.length, failed: results.filter((r) => !r.ok).length });
  } catch (err) {
    console.error("check-links error:", err);
    return res.status(500).json({ error: "A server error occurred." });
  }
}
